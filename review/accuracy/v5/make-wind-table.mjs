// Write api/_lib/wind-table.js — the wind rule the app carries — from the scored results (score5.mjs →
// review/accuracy/v2/results/v5-score.json), exactly as PLAN.md §2–§3, §6 and §7a decide it. Nothing is refit: the
// table shipped is the one every number in the results scored (2025, three source guesses averaged, clamped [0.7, 1.6]).
//   node review/accuracy/v5/make-wind-table.mjs [--check]
// --check: exit 1 if the committed table differs from what this would write (the drift gate).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const RESULTS = path.resolve(here, '../v2/results/v5-score.json');
const TARGET = path.resolve(here, '../../../api/_lib/wind-table.js');
if (!existsSync(RESULTS)) throw new Error('run review/accuracy/v5/score5.mjs first');
const res = JSON.parse(readFileSync(RESULTS, 'utf8'));
const dec = res.decisions;

const rule = dec.wind.ship;                    // 'BC' | 'MC' | 'M' | null
const ratios = rule === 'BC' ? res.tables.B : rule === 'MC' ? res.tables.M : null;
if (rule && dec.wind.westernCapeUnclamped) throw new Error('Western Cape unclamped: not handled — the test said no on 28 Sept; revisit before shipping');
const table = {
  id: 'v5-2025-three-guesses',
  rule,
  learnedOn: `${res.train.from}..${res.train.to}`,
  provenOn: `${res.test.from}..${res.test.to}`,
  // regions the table was learned in (one or more airports each); anywhere else keeps today's blend
  regions: ratios ? Object.keys(ratios) : [],
  blockedRegions: rule ? [...new Set([...(dec.wind[rule].blocked || []), ...(dec.wind[rule].liveSignBlocked || [])])].sort() : [],
  strandBlocked: Boolean(dec.wind.strandBlocked),
  headline: rule ? { ships: Boolean(dec.headline?.ships), thresholdKph: dec.headline?.T ?? null } : { ships: false, thresholdKph: null },
  ratios,
};

const text = `// GENERATED by review/accuracy/v5/make-wind-table.mjs — do not edit by hand; re-run it (and --check guards drift).
// The now-wind and the hourly winds: ${rule === 'BC' ? "today's weighted blend × a ratio per region × season × day-part" : rule ?? 'nothing passed — today everywhere'}
// (learned at 16 SA airports on 2025, the three source guesses averaged, clamped to [0.7, 1.6]; proven on 2026 — EVAL §12).
// Blocked (today's blend): ${table.blockedRegions.join(', ') || 'no region'}${table.strandBlocked ? '; within 15 km of Strand\'s station 68911 (the rule read too high there)' : ''}.
// The hero's Windy line on the corrected number: ${table.headline.ships ? `${table.headline.thresholdKph} km/h` : "today's 25 km/h on the raw blend"}.
export const WIND_TABLE = ${JSON.stringify(table, null, 2)};
`;

if (process.argv.includes('--check')) {
  const lf = (x) => x.replace(/\r\n/g, '\n');
  const now = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
  if (lf(now) !== lf(text)) { console.error('wind-table.js differs from the results — re-run make-wind-table.mjs'); process.exit(1); }
  console.log('wind-table.js matches the results');
} else {
  writeFileSync(TARGET, text);
  console.log(`wrote ${path.relative(process.cwd(), TARGET)}: rule ${rule}, blocked ${table.blockedRegions.join(', ') || '—'}, strand ${table.strandBlocked}, headline ${JSON.stringify(table.headline)}`);
}
