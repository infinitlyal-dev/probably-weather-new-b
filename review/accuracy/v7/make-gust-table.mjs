// Writes api/_lib/gust-table.js from v7's results (results-score7.json) and the towns each shipped station covers
// (towns.json, written by hand from the coverage rule — PLAN §4 and §8.6 — and reviewed by Fable).
//   node review/accuracy/v7/make-gust-table.mjs [--check]
// Decisions, all mechanical from the results:
//   - a region's headline rule ships where its verdict is 'ships' (bars 1–3 under all three guesses + leave-one-out);
//   - the Strand zone (15 km of 68911): its own rule if its own row ships; today's if its row cries wolf (bar 2) where
//     the Western Cape ships; otherwise it follows the Western Cape;
//   - a station's gust correction ships where §4's bar passed and towns.json lists what it covers; it feeds the
//     headline too unless R2 cried wolf in its region (then the corrected gust is shown, the ladder reads the raw one).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '../../../api/_lib/gust-table.js');
const res = JSON.parse(readFileSync(path.join(here, 'results-score7.json'), 'utf8'));
const towns = existsSync(path.join(here, 'towns.json')) ? JSON.parse(readFileSync(path.join(here, 'towns.json'), 'utf8')) : {};

const regions = {};
for (const [name, r] of Object.entries(res.regions)) {
  if (name === 'Strand zone' || r.verdict !== 'ships') continue;
  regions[name] = { rule: r.candidate.rule, gustLineKph: r.candidate.G, sourcesAt25: r.candidate.K };
}
const z = res.regions['Strand zone'];
const strandZone = z?.verdict === 'ships' ? { rule: z.candidate.rule, gustLineKph: z.candidate.G, sourcesAt25: z.candidate.K }
  : regions['Western Cape'] && z?.verdict === 'blocked (cries wolf)' ? { rule: 'today' } : null;

const stations = [];
for (const [id, c] of Object.entries(res.corrections)) {
  if (!c.ships || !towns[id]?.towns?.length) continue;
  const st = res.stations.find((s) => s.id === id);
  const cell = res.regions[c.region];
  const headline = !(cell?.R2 && cell.R2.stations.includes(id) && !cell.R2.ships);
  stations.push({ id, name: c.name, lat: st.lat, lon: st.lon, sectors: Object.values(c.sectors).map((s) => s.ratio), headline, towns: towns[id].towns });
}

const body = `// GENERATED by review/accuracy/v7/make-gust-table.mjs from review/accuracy/v7/results-score7.json — do not edit.
// Gust rules per region and gust corrections per SA Weather Service station (PLAN review/accuracy/v7/PLAN.md, EVAL §14).
// regions: the Windy rung's gust line (km/h) and "enough sources at 25 km/h" count, where that region's test passed.
// stations: each gust × sectors[N, NE, E, SE, S, SW, W, NW] (Open-Meteo's bearing) at the towns listed (within 5 km).
export const GUST_TABLE = ${JSON.stringify({ id: 'v7-2026-09-28', regions, strandZone, stations }, null, 2)};
`;
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== body) { console.error('gust-table.js is out of date with results-score7.json / towns.json'); process.exit(1); }
  console.log('gust-table.js matches the results');
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}: ${Object.keys(regions).length} regions, strand zone ${JSON.stringify(strandZone)}, ${stations.length} stations`);
}
