// Write api/_lib/wind-weights.js — wind's own say-per-source where the v6 test passed — from the scored results
// (score6.mjs → review/accuracy/v2/results/v6-score.json), exactly as PLAN.md §1 with §4a decides it. Nothing is refit:
// the weights and k shipped are the ones the prove half scored.
//   node review/accuracy/v6/make-wind-weights.mjs [--check]
// --check: exit 1 if the committed file differs from what this would write (the drift gate).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const RESULTS = path.resolve(here, '../v2/results/v6-score.json');
const TARGET = path.resolve(here, '../../../api/_lib/wind-weights.js');
if (!existsSync(RESULTS)) throw new Error('run review/accuracy/v6/score6.mjs first');
const res = JSON.parse(readFileSync(RESULTS, 'utf8'));
const dec = res.decisions;
// v8 (review/accuracy/v8/PLAN.md §4, EVAL §16): the Highveld's frozen v6 weights re-scored on the recorder's extra days
// under v6's bar; it joins only if that re-score says so.
const V8 = path.resolve(here, '../v8/results-highveld.json');
const v8Highveld = existsSync(V8) && JSON.parse(readFileSync(V8, 'utf8')).highveld?.ships === true;
const ships = [...new Set([...Object.entries(dec.regions).filter(([, d]) => d.rule === 'LW').map(([reg]) => reg), ...(v8Highveld ? ['Highveld'] : [])])].sort();
if (Object.values(dec.regions).some((d) => d.rule.startsWith('AW'))) throw new Error('AW passed somewhere: not handled — the test said no on 28 Sept; revisit before shipping');
if (dec.strandZone !== 'today') throw new Error('the Strand zone changed rule: not handled — revisit before shipping');
if (dec.missingFallback) throw new Error('the missing-source fallback fired: not handled — revisit before shipping');

const weights = {
  id: 'v6-live-2026-09-28',
  sources: ['Open-Meteo', 'WeatherAPI', 'Pirate Weather', 'MET Norway', 'Tomorrow.io'],
  window: res.live.window,
  // the hourly winds (days 0–1: OM, WA, MET, TI) take the same weights renormalised × k4 only if the proxy gate passed
  hourlyFollows: Boolean(dec.hourlyFollowsLW),
  regions: Object.fromEntries(ships.map((reg) => {
    const m = res.live.LW[reg];
    return [reg, { airport: res.live.region[reg].airport, weights: m.weights, k: m.k.k, k4: m.k4.k }];
  })),
};

const text = `// GENERATED by review/accuracy/v6/make-wind-weights.mjs — do not edit by hand; re-run it (and --check guards drift).
// Wind's own say-per-source (review/accuracy/v6/PLAN.md, EVAL §13): in the regions below the now-wind is each real
// source's own wind weighted by how right it was at the region's airport (1 / squared error, clamped 0.05–0.50, on the
// first half of the recorder's readings 25–28 Sept 2026) × k, proven on the second half (the Highveld on the readings to
// 29 Sept, v8). Everywhere else: the v5 rule
// (wind-table.js). Order: ${weights.sources.join(', ')}.
// Regions: ${ships.join(', ') || 'none'}. Hourly winds follow: ${weights.hourlyFollows ? 'yes (OM, WA, MET, TI renormalised × k4)' : 'no'}.
export const WIND_WEIGHTS = ${JSON.stringify(weights, null, 2)};
`;

if (process.argv.includes('--check')) {
  const lf = (x) => x.replace(/\r\n/g, '\n');
  const now = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
  if (lf(now) !== lf(text)) { console.error('wind-weights.js differs from the results — re-run make-wind-weights.mjs'); process.exit(1); }
  console.log('wind-weights.js matches the results');
} else {
  writeFileSync(TARGET, text);
  console.log(`wrote ${path.relative(process.cwd(), TARGET)}: ${ships.join(', ') || 'no region'}; hourly follows ${weights.hourlyFollows}`);
}
