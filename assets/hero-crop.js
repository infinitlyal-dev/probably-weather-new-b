/**
 * The desktop polaroid's crop for a background src, or null for the desktop CSS default.
 * @param {string} src
 * @returns {number|null} 0-100
 */
export function heroCropDesktopFor(src, table = HERO_CROP_OFFSETS, overrides = HERO_CROP_DESKTOP_OVERRIDES) {
  const key = heroCropKey(src);
  if (!key) return null;
  if (Object.prototype.hasOwnProperty.call(overrides, key)) {
    const value = overrides[key];
    if (typeof value !== 'number' || !Number.isFinite(value) || value < 0 || value > 100) return null;
    return value;
  }
  return heroCropFor(src, table);
}

/** Apply (or clear) the desktop polaroid's crop — same contract as applyHeroCrop. */
export function applyHeroCropDesktop(root, crop) {
  if (!root || !root.style) return;
  if (crop == null) root.style.removeProperty('--hero-crop-desktop');
  else root.style.setProperty('--hero-crop-desktop', `${crop}%`);
}
